# Operadores

a = 10
b = 5

#Maior que
print(a > b) 

#Menor que
print(a < b)

#Igual
print(a == b)

#Diferente
print(a != b)

#Maior ou Igual
print(a >= b)

#Menor ou Igual
print(a <= b)

#Operadores Lógicos
numero = 10

print('Operadores Lógicos')
#No AND o resultado é TRUE se os dois lados forem TRUE
print(numero > 5 and numero < 15)

#No OR o resultado é TRUE se somente um dos lados for TRUE
print (numero < 5 or numero== 10)


#NOT pega o bool original e nega ele
print(not (numero > 5))