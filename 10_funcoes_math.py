import math


#Inteiro para cima.
print(math.ceil(4.2))

#Inteiro para baixo.
print(math.floor(3.9))

#Mod = restante de uma divisão.
print(math.fmod(9,4))

#Raiz Quadrada.
print(math.sqrt(36))

#Funções padrões.
lista = [10, 20, 30, 40]
tam = len (lista)
print ("A lista", lista, "tem tamanho", tam)

#Lista soma.
soma = sum(lista)
print("A lista", lista, "tem um somatório", soma)